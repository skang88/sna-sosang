LAST = {'first': 29, 'mid': 30, 'last': 33}

def table(rows, widths, left_cols=()):
    nr, nc = len(rows), len(rows[0])
    t = d.add_table(nr, nc, width=TEXT_W, border_fill_id_ref=17, para_pr_id_ref=2)
    tot = sum(widths)
    t.set_column_widths([round(TEXT_W * w / tot) for w in widths])
    for r in range(nr):
        kind = HDR if r == 0 else (LAST if r == nr - 1 else BODY)
        for c in range(nc):
            pos = 'first' if c == 0 else ('last' if c == nc - 1 else 'mid')
            cell = t.cell(r, c)
            cell.element.set('borderFillIDRef', str(kind[pos]))
            cell.set_text(rows[r][c])
            for cp in cell.paragraphs:
                left = (r > 0 and c in left_cols)
                cp.element.set('paraPrIDRef', '1' if left else '28')
                for run in cp.runs:
                    run.element.set('charPrIDRef', str(BOLD41 if r == 0 else 41))
    return t

