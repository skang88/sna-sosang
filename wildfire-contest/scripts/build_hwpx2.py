h2('2. 조직 간 회복력: 소통과 협력')
p('Harris와 Doerfel(2017, p. 76)은 회복력 과정을 문제를 인식하고 즉흥적으로 해법을 만들어 가는 "담론적 활동과 조직화 활동의 혼합"으로 정의한다. 사회적 회복력은 지역사회의 파트너십을 통해 이루어지며, 조직들은 이 파트너십을 거쳐 유형·무형의 자원에 접근한다. 재난 상황에서는 이러한 네트워크화된 파트너십 자체가 대응과 재건의 핵심 자원이 된다.')
p('이들은 협력이 "말과 행동을 함께 담은 소통 활동"이며, 재난 지역의 협력은 재난 이전부터 있던 관계에 크게 의존한다고 본다(Harris & Doerfel, 2017, p. 77). Doerfel 등(2013)도 허리케인 카트리나 이후 조직들의 관계망을 추적하여, 재난 이전의 관계와 연결 방식이 재난 이후 재건에 핵심적인 역할을 한다는 점을 보였다. Kapucu(2006) 역시 재난 시 효과적인 기관 간 조정을 위해서는 재난 이전에 다른 조직과의 소통 체계를 갖추어 두어야 한다고 강조한다. 이 관점에서 대응기에 만들어진 관계가 복구기까지 유지되는지는 조직 간 회복력을 가늠하는 지표가 된다.')
p('회복력을 소통의 과정으로 보는 관점은 Buzzanell(2010)의 회복력 소통 이론과도 맞닿는다. 그는 회복력이 개인의 특성이 아니라 소통을 통해 구성되며, 사람과 조직이 말과 상호작용으로 "새로운 일상(new normalcy)"을 만들어 가는 과정이라고 본다. 이에 따르면 지원 기관들이 무엇에 대해 함께 말하는지, 그리고 그 담론이 재난에서 일상으로 어떻게 옮겨 가는지는 회복 과정 자체의 한 측면이다. 이는 연구 질문 (4)의 근거가 된다.')
p('이 연구에서 소상공인 지원은 이러한 협력의 전형이다. 도가 자금을 발표하고, 신용보증재단이 보증을 서고, 은행이 대출을 집행하고, 군이 접수를 받는 구조는 여러 조직의 공동 활동 없이는 작동하지 않는다. 지원 기관들이 함께 발표하고 함께 보도되는 것은 이 공동 활동이 공적으로 드러난 흔적이며, 이 연구가 언론 보도를 자료로 삼는 근거가 된다.')

h2('3. 네트워크의 구조: 중심성·중앙화·중개')
p('Harris와 Doerfel(2017, pp. 77–78)은 특정 조직 하나의 연결보다, 공공·민간·비영리 부문에 걸친 여러 조직의 다중 관계를 함께 보는 네트워크화된 이해관계자 모형을 제시한다. 이 모형에서 주목하는 요소는 다음과 같다.')
item('1)', '관계의 강도와 잠재 관계: 강한 관계는 촘촘한 협력망을 만들어 자원 공유를 쉽게 하고, 약한 관계는 재난 이후 특정 조직에 대한 의존을 줄인다. 평소 드러나지 않던 잠재 관계는 재난 이후 활성화되어 네트워크의 중복성을 높인다.')
item('2)', '중심성과 중개자: 연결이 많은 조직(연결 중심성)은 네트워크에서 두드러진 역할을 한다. 서로 떨어진 조직들을 이어 주는 중개자(매개 중심성)는 공식 대응과 자발적·신생 조직의 활동을 조정한다.')
item('3)', '중심성과 중앙화의 구분: 중심성은 개별 조직이 얼마나 잘 연결되었는지를, 중앙화는 네트워크 전체가 소수 조직을 중심으로 조직되었는지를 나타낸다. 중앙화가 높으면 정보가 소수 조직을 거쳐 흐르고, 낮으면 특정 조직의 통제 없이 퍼진다.')
p('이 개념들은 Freeman(1978)이 정식화하였다. 그는 연결·근접·매개라는 세 가지 중심성을 구분하고, 가장 중심적인 행위자와 나머지 행위자의 중심성 차이를 이론적 최댓값으로 나눈 값을 네트워크 중앙화로 정의하였다. 이 연구의 연결 중앙화와 매개 중심성은 이 정의를 따른다.')
p('중개 역할은 행위자가 속한 집단을 함께 고려하면 더 구체적으로 구분된다. Gould와 Fernandez(1989)는 접근이나 신뢰가 부족한 두 행위자 사이를 잇는 중개를 집단 소속에 따라 조정자(coordinator), 순회자(itinerant), 문지기(gatekeeper), 대표자(representative), 연락자(liaison)의 다섯 유형으로 나누었다. 재난 맥락에서 Kapucu(2006)는 기관 사이의 경계를 넘나들며 정보를 잇는 경계 연결자(boundary spanner)가 다기관 조정의 핵심이라고 보았다. 광역 금융기관과 현지 소상공인 사이에서 어떤 기관이 이 역할을 맡는지는 연구 질문 (2)의 핵심이다.')

h2('4. 재난 단계와 네트워크의 변화')
p('재난 대응 조직은 사전 계획대로만 움직이지 않는다. Drabek과 McEntire(2003)는 재난 시 계획에 없던 집단과 행동이 생겨나는 신생 현상(emergent phenomena)이 재난 연구의 핵심 주제임을 정리하고, 관료제적 지휘·통제 접근의 한계를 지적하였다. Choi와 Brower(2006)는 지방 재난관리 네트워크를 분석하여 실제 실무 관계가 정부 계획에 정해진 관계와 다르게 작동한다는 점을 보였다. Comfort와 Kapucu(2006)는 9·11 대응에서 조직 간 조정이 사건 전개에 따라 확장되고 재편되는 동적 네트워크로 이루어졌음을 보였다.')
p('따라서 재난 네트워크는 시기에 따라 다른 모습을 띤다. Harris와 Doerfel(2017)은 비상 대응기에서 전환기, 복구기로 넘어가며 소통의 패턴과 조직 간 관계가 함께 바뀐다고 보고, 대응에서 장기 복구로 가며 중앙화가 어떻게 변하는지를 핵심 질문으로 삼았다. 대응기에 긴급하게 생긴 연결이 복구기까지 이어지는지, 아니면 사라지고 새 관계로 대체되는지가 이 연구의 연구 질문 (1)과 (3)이 묻는 바이다.')
p('복구가 끝나기 전에 다른 재난이 겹치면 이 흐름은 더 복잡해진다. de Ruiter 등(2020)은 영향이 공간적·시간적으로 겹치는 연속 재난(consecutive disasters)이 단일 재난과 뚜렷이 다른 영향을 낳으며, 기존 위험 평가와 정책은 이를 제대로 다루지 못한다고 지적하였다. 4개월 사이 산불과 극한호우를 연달아 겪은 산청은 연속 재난이 복구기 지원 네트워크를 어떻게 바꾸는지 볼 수 있는 사례이다.')

h2('5. 협력적 거버넌스와 수요자 조직의 참여')
p('Ansell과 Gash(2008)는 협력적 거버넌스를 공공기관이 비국가 이해관계자와 함께 공식적·합의 지향적 의사결정을 하는 체계로 정의하고, 협력의 성패를 좌우하는 출발 조건으로 참여자 간 권력·자원의 불균형, 참여 유인, 과거의 협력·갈등 이력을 들었다. 이 관점에서 지원을 공급하는 기관과 지원을 받는 소상공인 조직 사이에는 자원과 정보의 불균형이 있으며, 수요자 조직이 언제, 어떤 위치로 참여하는지가 협력의 질을 좌우한다.')
p('국내 연구도 같은 방향을 가리킨다. 이용숙 등(2018)은 세월호 참사 이후 안산의 재난 대응 거버넌스에서, 네트워크 영향력은 크지 않았던 피해 지역의 서비스 제공형 NGO가 자원 연계와 갈등 완화 같은 중재자 역할을 맡았음을 보였다. 임정빈(2020)은 경기도 재난안전 로컬거버넌스를 네트워크로 분석하여, 민간 시민사회 조직과의 연계를 강화하고 거버넌스를 민간 부문까지 넓혀야 한다고 제안하였다. 이는 소상공인 단체 같은 지역 수요자 조직이 지원 거버넌스에서 어떤 위치에 있는지를 따로 살펴야 하는 근거가 된다.')

